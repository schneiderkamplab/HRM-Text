def finalize(args: argparse.Namespace) -> None:
    decisions: set[str] = set()
    rejected_by_file: dict[str, set[int]] = {}
    errors = 0
    rejected_reasons: Counter[str] = Counter()
    for path in args.audit:
        with path.open(encoding="utf-8") as handle:
            for line in handle:
                if not line.strip():
                    continue
                verdict = json.loads(line)
                row_id = str(verdict["row_id"])
                if row_id in decisions:
                    raise ValueError(f"duplicate audit decision: {row_id}")
                decisions.add(row_id)
                if "error" in verdict:
                    errors += 1
                if not verdict.get("keep"):
                    filename, line_number = row_id.rsplit(":", 1)
                    rejected_by_file.setdefault(filename, set()).add(int(line_number))
                    rejected_reasons[str(verdict.get("primary_failure_type", "other"))] += 1
    if len(decisions) != args.expected_rows:
        raise ValueError(f"audit coverage {len(decisions)} != {args.expected_rows}")
    if errors:
        raise ValueError(f"full audit contains {errors} judge errors")

    sources = sorted((args.input / "data").glob("*.jsonl.gz"))
    if not sources:
        raise FileNotFoundError(args.input / "data")
    if args.output.exists():
        if not args.force:
            raise FileExistsError(args.output)
        shutil.rmtree(args.output)
    (args.output / "data").mkdir(parents=True)
    work = [
        (source, args.output / "data" / source.name, rejected_by_file.get(source.name, set()))
        for source in sources
    ]
    with ProcessPoolExecutor(max_workers=min(args.workers, len(work))) as pool:
        shard_counts = list(pool.map(_filter_audited_shard, work))
    totals: Counter[str] = Counter()
    for shard in shard_counts:
        totals.update({key: value for key, value in shard.items() if key in {"seen", "kept", "rejected"}})
    if totals["seen"] != args.expected_rows:
        raise ValueError(f"source rows {totals['seen']} != {args.expected_rows}")
    if totals["rejected"] != sum(map(len, rejected_by_file.values())):
        raise ValueError("not all rejected row IDs mapped to source shards")
    manifest = {
        "name": FINAL_PACKAGE_NAME,
        "intended_hf_id": FINAL_HF_ID,
        "upload_performed": False,
        "source_package": str(args.input),
        "source_repo": "schneiderkamplab/dfm10-folketingets-dokumenter-error-correction",
        "source_revision": SOURCE_REVISION,
        "license": "cc-by-4.0",
        "filter_contract": "folketing_error_correction_contract_v1_plus_full_task_aware_audit",
        "admission_status": "fully_audited",
        "counts": dict(totals),
        "data_files": [
            {
                "file": shard["file"],
                "rows": shard["kept"],
                "bytes": shard["bytes"],
                "sha256": shard["sha256"],
            }
            for shard in shard_counts
        ],
        "rejected_reasons": dict(rejected_reasons),
        "audit_files": [str(path) for path in args.audit],
    }
    atomic_write_json(args.output / "metadata" / "manifest.json", manifest)
    (args.output / "README.md").write_text(final_readme(manifest), encoding="utf-8")
    validator = args.output / "validate_dataset.py"
    validator.write_text(FINAL_VALIDATOR, encoding="utf-8")
    validator.chmod(0o755)
    print(json.dumps(manifest, indent=2, sort_keys=True))


def record_upload(args: argparse.Namespace) -> None:
    from huggingface_hub import HfApi, hf_hub_download

    token = os.environ.get(args.token_env)
    if not token:
        raise ValueError(f"missing Hugging Face token in ${args.token_env}")
    manifest_path = args.package / "metadata/manifest.json"
    manifest = json.loads(manifest_path.read_text())
    if manifest.get("intended_hf_id") != args.repo_id:
        raise ValueError("package intended_hf_id does not match upload repo")

    manifest["upload_performed"] = True
    atomic_write_json(manifest_path, manifest)
    api = HfApi(token=token)
    commit = api.upload_file(
        path_or_fileobj=str(manifest_path),
        path_in_repo="metadata/manifest.json",
        repo_id=args.repo_id,
        repo_type="dataset",
        commit_message="Record verified DFM11 Folketing audit package",
        token=token,
    )
    revision = api.dataset_info(args.repo_id, token=token).sha
    expected = {
        path.relative_to(args.package).as_posix()
        for path in args.package.rglob("*")
        if path.is_file() and ".cache" not in path.parts and "__pycache__" not in path.parts
    }
    remote = set(api.list_repo_files(args.repo_id, repo_type="dataset", revision=revision, token=token))
    missing = sorted(expected - remote)
    if missing:
        raise ValueError(f"remote upload is missing files: {missing[:10]}")
    downloaded_manifest = Path(
        hf_hub_download(
            args.repo_id,
            "metadata/manifest.json",
            repo_type="dataset",
            revision=revision,
            token=token,
        )
    )
    if downloaded_manifest.read_bytes() != manifest_path.read_bytes():
        raise ValueError("remote manifest differs from local manifest")

    config = args.config.read_text()
    if "revision: pending_full_audit_upload" not in config:
        if f"revision: {revision}" not in config:
            raise ValueError("DFM11 config has neither pending nor current upload revision")
    else:
        config = config.replace("revision: pending_full_audit_upload", f"revision: {revision}", 1)
    pending_rows = "available_rows: pending_full_audit"
    if pending_rows in config:
        config = config.replace(pending_rows, f"available_rows: {manifest['counts']['kept']}", 1)
    pending_status = "admission_status: full_task_aware_audit_in_progress"
    if pending_status in config:
        config = config.replace(pending_status, "admission_status: fully_audited", 1)
    temporary = args.config.with_name(f".{args.config.name}.tmp.{os.getpid()}")
    temporary.write_text(config, encoding="utf-8")
    os.replace(temporary, args.config)

    receipt = {
        "repo_id": args.repo_id,
        "revision": revision,
        "commit_url": str(commit.commit_url),
        "expected_files": len(expected),
        "missing": missing,
        "manifest_match": True,
        "rows": manifest["counts"]["kept"],
    }
    atomic_write_json(args.receipt, receipt)
    print(json.dumps(receipt, indent=2, sort_keys=True))


def gate(args: argparse.Namespace) -> None:
    decisions: dict[str, dict[str, Any]] = {}
    errors = 0
    for path in args.audit:
        with path.open(encoding="utf-8") as handle:
            for line in handle:
                if not line.strip():
                    continue
                row = json.loads(line)
                decisions[str(row["row_id"])] = row
                errors += "error" in row
    kept = sum(row.get("keep") is True for row in decisions.values())
    keep_rate = kept / len(decisions) if decisions else 0.0
    failures = []
    if len(decisions) != args.expected_rows:
        failures.append(f"audited rows {len(decisions)} != {args.expected_rows}")
    if errors:
        failures.append(f"judge errors {errors} != 0")
    if keep_rate < args.minimum_keep_rate:
        failures.append(f"keep rate {keep_rate:.3%} < {args.minimum_keep_rate:.3%}")
    result = {
        "passed": not failures,
        "audited_rows": len(decisions),
        "kept_rows": kept,
        "keep_rate": keep_rate,
        "judge_errors": errors,
        "minimum_keep_rate": args.minimum_keep_rate,
        "audit_files": [str(path) for path in args.audit],
        "failures": failures,
    }
    atomic_write_json(args.output, result)
    print(json.dumps(result, indent=2, sort_keys=True))
    if failures:
        raise SystemExit(1)


