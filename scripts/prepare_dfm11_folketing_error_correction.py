def corruption_edit_count(source: str, target: str) -> int | None:
    """Return the minimum declared OCR edits mapping target to source."""
    states: dict[int, int] = {0: 0}
    for char in target:
        next_states: dict[int, int] = {}
        replacement = CONFUSIONS.get(char)
        for source_index, edits in states.items():
            if source.startswith(char, source_index):
                end = source_index + len(char)
                next_states[end] = min(next_states.get(end, edits), edits)
            if replacement and source.startswith(replacement, source_index):
                end = source_index + len(replacement)
                changed = edits + 1
                next_states[end] = min(next_states.get(end, changed), changed)
        if not next_states:
            return None
        states = next_states
    return states.get(len(source))


def target_quality_failure(text: str) -> str | None:
    if len(text) < 100 or len(WORD_RE.findall(text)) < 20:
        return "target_too_short"
    if CONTROL_RE.search(text) or "\ufffd" in text:
        return "target_control_or_replacement_character"
    alnum = sum(char.isalnum() for char in text)
    if alnum / max(1, len(text)) < 0.18:
        return "target_low_alphanumeric_density"

    letters = [char for char in text if char.isalpha()]
    non_latin = sum("LATIN" not in unicodedata.name(char, "") for char in letters)
    if non_latin / max(1, len(letters)) > 0.002:
        return "target_non_latin_ocr_artifacts"

    lines = [line.strip() for line in text.splitlines() if line.strip()]
    fragment_lines = sum(sum(char.isalnum() for char in line) <= 2 for line in lines)
    if len(lines) >= 8 and fragment_lines / len(lines) >= 0.25:
        return "target_fragmented_lines"
    if len(DOT_LEADER_RE.findall(text)) >= 4:
        return "target_index_or_dot_leaders"
    return None


def validate_row(row: dict[str, Any]) -> tuple[str | None, int | None]:
    messages = row.get("messages")
    if not isinstance(messages, list) or len(messages) != 2:
        return "invalid_message_shape", None
    user, assistant = messages
    if user.get("role") != "user" or assistant.get("role") != "assistant":
        return "invalid_message_roles", None
    prompt = user.get("content")
    target = assistant.get("content")
    if not isinstance(prompt, str) or not isinstance(target, str):
        return "non_string_content", None
    if not prompt.startswith(PROMPT_PREFIX):
        return "unexpected_prompt", None

    source = prompt[len(PROMPT_PREFIX) :]
    failure = target_quality_failure(target)
    if failure:
        return failure, None
    edits = corruption_edit_count(source, target)
    if edits is None:
        return "source_target_not_declared_corruption", None
    if edits == 0:
        return "normalized_noop", edits
    if edits > 8:
        return "too_many_corruptions", edits
    return None, edits


def atomic_write_json(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.tmp.{os.getpid()}")
    with temporary.open("w", encoding="utf-8") as handle:
        json.dump(value, handle, ensure_ascii=False, indent=2, sort_keys=True)
        handle.write("\n")
        handle.flush()
        os.fsync(handle.fileno())
    os.replace(temporary, path)


def filter_shard(source: Path, destination: Path) -> dict[str, Any]:
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = destination.with_name(f".{destination.name}.tmp.{os.getpid()}")
    counts: Counter[str] = Counter()
    digest = hashlib.sha256()
    try:
        with gzip.open(source, "rt", encoding="utf-8") as reader, gzip.open(
            temporary, "wt", encoding="utf-8", compresslevel=6
        ) as writer:
            for line_number, line in enumerate(reader, start=1):
                counts["rows_seen"] += 1
                try:
                    row = json.loads(line)
                except json.JSONDecodeError:
                    counts["reject:invalid_json"] += 1
                    continue
                failure, edits = validate_row(row)
                if failure:
                    counts[f"reject:{failure}"] += 1
                    continue
                row.setdefault("metadata", {})["dfm11_repair"] = {
                    "name": "folketing_error_correction_contract_v1",
                    "declared_ocr_edits": edits,
                    "source_revision": SOURCE_REVISION,
                }
                encoded = (json.dumps(row, ensure_ascii=False, separators=(",", ":")) + "\n").encode()
                writer.write(encoded.decode())
                digest.update(encoded)
                counts["rows_kept"] += 1
                counts[f"kept_edits:{edits}"] += 1
        os.replace(temporary, destination)
    finally:
        temporary.unlink(missing_ok=True)
    return {
        "source": str(source),
        "output": str(destination),
        "sha256_uncompressed": digest.hexdigest(),
        "counts": dict(counts),
    }


def build(args: argparse.Namespace) -> None:
    sources = sorted((args.input / "data").glob("train-*.jsonl.gz"))
    if not sources:
        raise FileNotFoundError(args.input / "data")
    if args.output.exists():
        if not args.force:
            raise FileExistsError(args.output)
        shutil.rmtree(args.output)
    (args.output / "data").mkdir(parents=True)
    work = [(source, args.output / "data" / source.name) for source in sources]
    with ProcessPoolExecutor(max_workers=min(args.workers, len(work))) as pool:
        results = list(pool.map(filter_shard, *(zip(*work))))

    totals: Counter[str] = Counter()
    for result in results:
        totals.update(result["counts"])
    manifest = {
        "name": args.output.name,
        "source_repo": "schneiderkamplab/dfm10-folketingets-dokumenter-error-correction",
        "source_revision": SOURCE_REVISION,
        "license": "cc-by-4.0",
        "filter_contract": "folketing_error_correction_contract_v1",
        "counts": dict(totals),
        "shards": results,
        "admission_status": "deterministically_filtered_pending_5000_row_audit",
    }
    atomic_write_json(args.output / "metadata" / "manifest.json", manifest)
    print(json.dumps(manifest["counts"], indent=2, sort_keys=True))


def sample(args: argparse.Namespace) -> None:
    sources = sorted((args.input / "data").glob("*.jsonl.gz"))
    if not sources:
        raise FileNotFoundError(args.input / "data")
    if args.output.exists():
        if not args.force:
            raise FileExistsError(args.output)
        shutil.rmtree(args.output)
    heap: list[tuple[int, int, dict[str, Any]]] = []
    ordinal = 0
    for source in sources:
        with gzip.open(source, "rt", encoding="utf-8") as handle:
            for line in handle:
                row = json.loads(line)
                source_id = str(row.get("metadata", {}).get("source_id") or ordinal)
                value = int.from_bytes(
                    hashlib.blake2b(f"{args.seed}\0{source_id}".encode(), digest_size=8).digest(),
                    "big",
                )
                item = (-value, ordinal, row)
                if len(heap) < args.rows:
                    heapq.heappush(heap, item)
                elif value < -heap[0][0]:
                    heapq.heapreplace(heap, item)
                ordinal += 1
    if len(heap) != args.rows:
        raise ValueError(f"requested {args.rows} rows, found {len(heap)}")
    selected = [item[2] for item in sorted(heap, key=lambda item: -item[0])]
    data = args.output / "data" / "sample.jsonl.gz"
    data.parent.mkdir(parents=True, exist_ok=True)
    temporary = data.with_name(f".{data.name}.tmp.{os.getpid()}")
    with gzip.open(temporary, "wt", encoding="utf-8", compresslevel=6) as handle:
        for row in selected:
            handle.write(json.dumps(row, ensure_ascii=False, separators=(",", ":")) + "\n")
    os.replace(temporary, data)
    atomic_write_json(
        args.output / "metadata" / "manifest.json",
        {"rows": len(selected), "seed": args.seed, "source": str(args.input)},
    )
    print(json.dumps({"output": str(args.output), "rows": len(selected), "population": ordinal}))


def audit_messages(row: dict[str, Any]) -> list[dict[str, str]]:
    messages = row["messages"]
    source = messages[0]["content"][len(PROMPT_PREFIX) :]
    target = messages[1]["content"]
    edits = row["metadata"]["dfm11_repair"]["declared_ocr_edits"]
    system = (
        "Du er en streng, opgavespecifik kvalitetskontrollør af dansk SFT-data. "
        "En deterministisk validator har allerede bevist, at inputtet blev dannet "
        "fra målet med præcis det oplyste antal syntetiske OCR-tegnfejl, og at målet "
        "retter dem alle uden andre ændringer. En forskel på kun 1-8 tegn er tilsigtet "
        "og må aldrig i sig selv føre til afvisning. Bedøm kun om målteksten er "
        "sammenhængende og nyttig dansk tekst uden alvorlige tilbageværende OCR-fejl, "
        "ufuldstændige fragmenter, registre/indholdsfortegnelser eller forkert sprog. "
        "Historisk dansk stavning og parlamentarisk sprog er gyldigt. Returnér kun JSON."
    )
    payload = {
        "synthetic_ocr_edits_proven_corrected": edits,
        "corrupted_input": source,
        "clean_target": target,
        "required_schema": {
            "keep": "boolean",
            "coherent_danish": "boolean",
            "residual_ocr_quality_ok": "boolean",
            "complete_non_list_text": "boolean",
            "useful_training_example": "boolean",
            "primary_failure_type": "none|residual_ocr|fragment_or_list|wrong_language|low_value|other",
            "complaint": "short string; none when keep=true",
        },
    }
    return [
        {"role": "system", "content": system},
        {"role": "user", "content": json.dumps(payload, ensure_ascii=False)},
    ]


def call_audit(args: argparse.Namespace, row: dict[str, Any], row_id: str) -> dict[str, Any]:
    body = {
        "model": args.model,
        "messages": audit_messages(row),
        "temperature": 0,
        "top_p": 1,
        # A small number of difficult rows consume substantial hidden reasoning
        # before emitting the constrained JSON object.
        "max_tokens": 2048,
        "response_format": {
            "type": "json_schema",
            "json_schema": {
                "name": "folketing_error_correction_audit",
                "schema": AUDIT_JSON_SCHEMA,
                "strict": True,
            },
        },
    }
    last_error = ""
    for attempt in range(args.retries + 1):
        try:
            request = urllib.request.Request(
                args.base_url.rstrip("/") + "/chat/completions",
                data=json.dumps(body).encode(),
                headers={"Content-Type": "application/json", "Authorization": "Bearer dummy"},
                method="POST",
            )
            with urllib.request.urlopen(request, timeout=args.timeout) as response:
                payload = json.loads(response.read().decode())
            content = payload["choices"][0]["message"]["content"]
            match = re.search(r"\{.*\}", content, re.S)
            if match is None:
                raise ValueError("judge returned no JSON object")
            verdict = json.loads(match.group(0))
            required = (
                "coherent_danish",
                "residual_ocr_quality_ok",
                "complete_non_list_text",
                "useful_training_example",
            )
            keep = bool(verdict.get("keep")) and all(bool(verdict.get(key)) for key in required)
            return {
                "row_id": row_id,
                "keep": keep,
                "primary_failure_type": str(verdict.get("primary_failure_type") or ("none" if keep else "other")),
                "complaint": str(verdict.get("complaint") or ("none" if keep else "judge_rejected")),
                "judge": verdict,
                "judge_model": args.model,
            }
        except (
            urllib.error.URLError,
            http.client.HTTPException,
            ConnectionError,
            TimeoutError,
            KeyError,
            ValueError,
            json.JSONDecodeError,
        ) as exc:
            last_error = f"{type(exc).__name__}: {exc}"
            if attempt < args.retries:
                time.sleep(min(10, 2**attempt))
    return {
        "row_id": row_id,
        "keep": False,
        "primary_failure_type": "judge_error",
        "complaint": "judge_error",
        "error": last_error,
        "judge_model": args.model,
    }


def audit(args: argparse.Namespace) -> None:
    if not 0 <= args.partition_index < args.partitions:
        raise ValueError("partition index is outside partition count")
    if args.force and args.resume:
        raise ValueError("--force and --resume are mutually exclusive")
    source_files = sorted((args.input / "data").glob("*.jsonl.gz"))
    if not source_files:
        raise FileNotFoundError(args.input / "data")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    partial = args.output.with_suffix(args.output.suffix + ".partial")
    if args.force:
        args.output.unlink(missing_ok=True)
        partial.unlink(missing_ok=True)
    elif args.output.exists():
        if not args.resume:
            raise FileExistsError(args.output)
        output_has_errors = False
        with args.output.open(encoding="utf-8") as handle:
            for line in handle:
                if line.strip() and "error" in json.loads(line):
                    output_has_errors = True
                    break
        if not output_has_errors:
            print(json.dumps({"partition": args.partition_index, "status": "already_complete", "output": str(args.output)}))
            return
        os.replace(args.output, partial)
    elif partial.exists() and not args.resume:
        raise FileExistsError(f"partial audit exists; use --resume or --force: {partial}")

    completed_ids: set[str] = set()
    counts: Counter[str] = Counter()
    if partial.exists():
        cleaned_partial = partial.with_name(f".{partial.name}.clean.{os.getpid()}")
        with partial.open(encoding="utf-8") as handle, cleaned_partial.open("w", encoding="utf-8") as cleaned:
            for line in handle:
                if not line.strip():
                    continue
                verdict = json.loads(line)
                if "error" in verdict:
                    counts["retrying_error_rows"] += 1
                    continue
                row_id = str(verdict["row_id"])
                if row_id in completed_ids:
                    raise ValueError(f"duplicate partial audit decision: {row_id}")
                completed_ids.add(row_id)
                cleaned.write(line)
                counts["resumed_rows"] += 1
            cleaned.flush()
            os.fsync(cleaned.fileno())
        os.replace(cleaned_partial, partial)

    def selected_rows():
        for source in source_files:
            with gzip.open(source, "rt", encoding="utf-8") as handle:
                for line_number, line in enumerate(handle):
                    row_id = f"{source.name}:{line_number}"
                    partition = int.from_bytes(
                        hashlib.blake2b(row_id.encode(), digest_size=8).digest(), "big"
                    ) % args.partitions
                    if partition != args.partition_index:
                        continue
                    counts["selected_rows"] += 1
                    if row_id in completed_ids:
                        continue
                    yield json.loads(line), row_id

    try:
        mode = "a" if partial.exists() else "w"
        with partial.open(mode, encoding="utf-8") as output, ThreadPoolExecutor(max_workers=args.concurrency) as pool:
            iterator = iter(selected_rows())
            pending: dict[Any, None] = {}
            while True:
                while len(pending) < args.concurrency:
                    try:
                        row, row_id = next(iterator)
                    except StopIteration:
                        break
                    pending[pool.submit(call_audit, args, row, row_id)] = None
                if not pending:
                    break
                completed, _ = wait(pending, return_when=FIRST_COMPLETED)
                for future in completed:
                    pending.pop(future)
                    verdict = future.result()
                    output.write(json.dumps(verdict, ensure_ascii=False, separators=(",", ":")) + "\n")
                    output.flush()
                    counts["rows"] += 1
                    counts["keep" if verdict["keep"] else "drop"] += 1
                    if "error" in verdict:
                        counts["judge_errors"] += 1
                    if counts["rows"] % 100 == 0:
                        output.flush()
                        os.fsync(output.fileno())
                        print(
                            f"partition={args.partition_index} new={counts['rows']} "
                            f"resumed={counts['resumed_rows']} selected={counts['selected_rows']}",
                            flush=True,
                        )
            output.flush()
            os.fsync(output.fileno())
        if counts["judge_errors"]:
            raise RuntimeError(
                f"partition {args.partition_index} has {counts['judge_errors']} unresolved judge errors; resume to retry"
            )
        os.replace(partial, args.output)
    except BaseException:
        raise
    print(json.dumps({"partition": args.partition_index, **counts}, sort_keys=True))


def sidecar_unresolved(args: argparse.Namespace) -> None:
    """Preserve repeatedly unresolved rows and exclude them fail-closed."""
    partitions = len(args.audit)
    completed_by_partition: list[set[str]] = []
    decision_paths: list[tuple[Path, Path]] = []
    decision_count = 0
    for output in args.audit:
        partial = output.with_suffix(output.suffix + ".partial")
        source = output if output.exists() else partial
        if not source.exists():
            raise FileNotFoundError(source)
        completed: set[str] = set()
        with source.open(encoding="utf-8") as handle:
            for line in handle:
                if not line.strip():
                    continue
                verdict = json.loads(line)
                if "error" in verdict:
                    raise ValueError(f"unresolved error verdict remains in {source}")
                row_id = str(verdict["row_id"])
                if row_id in completed:
                    raise ValueError(f"duplicate decision in {source}: {row_id}")
                completed.add(row_id)
        completed_by_partition.append(completed)
        decision_paths.append((source, output))
        decision_count += len(completed)

    unresolved: list[tuple[int, str, dict[str, Any]]] = []
    source_rows = 0
    for source in sorted((args.input / "data").glob("*.jsonl.gz")):
        with gzip.open(source, "rt", encoding="utf-8") as handle:
            for line_number, line in enumerate(handle):
                source_rows += 1
                row_id = f"{source.name}:{line_number}"
                partition = int.from_bytes(
                    hashlib.blake2b(row_id.encode(), digest_size=8).digest(), "big"
                ) % partitions
                if row_id not in completed_by_partition[partition]:
                    unresolved.append((partition, row_id, json.loads(line)))

    if source_rows != args.expected_rows:
        raise ValueError(f"source coverage {source_rows} != {args.expected_rows}")
    if decision_count + len(unresolved) != args.expected_rows:
        raise ValueError(
            f"decision coverage {decision_count} + {len(unresolved)} unresolved "
            f"!= {args.expected_rows}"
        )
    if len(unresolved) != args.expected_unresolved:
        raise ValueError(
            f"found {len(unresolved)} unresolved rows, expected {args.expected_unresolved}"
        )

    args.sidecar.parent.mkdir(parents=True, exist_ok=True)
    temporary = args.sidecar.with_name(f".{args.sidecar.name}.tmp.{os.getpid()}")
    with temporary.open("w", encoding="utf-8") as handle:
        for partition, row_id, row in unresolved:
            handle.write(
                json.dumps(
                    {
                        "row_id": row_id,
                        "partition": partition,
                        "resolution": "fail_closed_exclusion_after_repeated_no_json",
                        "row": row,
                    },
                    ensure_ascii=False,
                    separators=(",", ":"),
                )
                + "\n"
            )
        handle.flush()
        os.fsync(handle.fileno())
    os.replace(temporary, args.sidecar)

    unresolved_by_partition: dict[int, list[str]] = {}
    for partition, row_id, _ in unresolved:
        unresolved_by_partition.setdefault(partition, []).append(row_id)
    for partition, (source, output) in enumerate(decision_paths):
        additions = unresolved_by_partition.get(partition, [])
        if source == output:
            if additions:
                raise ValueError(f"complete partition {partition} has missing rows")
            continue
        with source.open("a", encoding="utf-8") as handle:
            for row_id in additions:
                handle.write(
                    json.dumps(
                        {
                            "row_id": row_id,
                            "keep": False,
                            "primary_failure_type": "unresolved_judge",
                            "complaint": "excluded after repeated schema-generation failure; preserved in sidecar",
                            "judge_model": args.judge_model,
                            "resolution": "fail_closed_exclusion",
                        },
                        ensure_ascii=False,
                        separators=(",", ":"),
                    )
                    + "\n"
                )
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(source, output)

    print(
        json.dumps(
            {
                "source_rows": source_rows,
                "existing_decisions": decision_count,
                "sidecar_unresolved": len(unresolved),
                "sidecar": str(args.sidecar),
                "resolution": "fail_closed_exclusion",
            },
            indent=2,
            sort_keys=True,
        )
    )


def _filter_audited_shard(work: tuple[Path, Path, set[int]]) -> dict[str, Any]:
    source, destination, rejected_lines = work
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = destination.with_name(f".{destination.name}.tmp.{os.getpid()}")
    seen = kept = rejected = 0
    try:
        with gzip.open(source, "rt", encoding="utf-8") as reader, gzip.open(
            temporary, "wt", encoding="utf-8", compresslevel=6
        ) as writer:
            for line_number, line in enumerate(reader):
                seen += 1
                if line_number in rejected_lines:
                    rejected += 1
                    continue
                writer.write(line)
                kept += 1
        os.replace(temporary, destination)
    finally:
        temporary.unlink(missing_ok=True)
    return {
        "file": f"data/{destination.name}",
        "seen": seen,
        "kept": kept,
        "rejected": rejected,
        "bytes": destination.stat().st_size,
        "sha256": hashlib.sha256(destination.read_bytes()).hexdigest(),
    }


FINAL_VALIDATOR = '''#!/usr/bin/env python3
import gzip, hashlib, json
from pathlib import Path

root = Path(__file__).parent
manifest = json.loads((root / "metadata/manifest.json").read_text())
rows = 0
for item in manifest["data_files"]:
    path = root / item["file"]
    if hashlib.sha256(path.read_bytes()).hexdigest() != item["sha256"]:
        raise ValueError(f"checksum mismatch: {path}")
    shard_rows = 0
    with gzip.open(path, "rt", encoding="utf-8") as handle:
        for line in handle:
            row = json.loads(line)
            messages = row.get("messages")
            repair = row.get("metadata", {}).get("dfm11_repair", {})
            if not isinstance(messages, list) or len(messages) != 2:
                raise ValueError(f"invalid messages in {path}:{shard_rows}")
            if messages[0].get("role") != "user" or messages[1].get("role") != "assistant":
                raise ValueError(f"invalid roles in {path}:{shard_rows}")
            if not str(messages[0].get("content", "")).startswith("Ret OCR- og tekstfejlene.\\n\\n"):
                raise ValueError(f"invalid prompt in {path}:{shard_rows}")
            if repair.get("declared_ocr_edits") not in range(1, 9):
                raise ValueError(f"invalid edit receipt in {path}:{shard_rows}")
            shard_rows += 1
    if shard_rows != item["rows"]:
        raise ValueError(f"row count mismatch: {path}: {shard_rows} != {item['rows']}")
    rows += shard_rows
if rows != manifest["counts"]["kept"]:
    raise ValueError(f"package row count mismatch: {rows}")
print(json.dumps({"valid": True, "rows": rows, "dataset": manifest["name"]}))
'''


